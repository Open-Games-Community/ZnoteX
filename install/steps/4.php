		</div>
	</form>

<?php else: ?>

	<?php if (!$report['errors']): ?>
		<p class="good">
			Done. <?= (int)$report['created'] ?> statement<?= $report['created'] === 1 ? '' : 's' ?> ran,
			<?= (int)$report['skipped'] ?> skipped as already populated.
			<?= (int)$report['tables'] ?> <code>znote_*</code> tables are now present.
		</p>
	<?php else: ?>
		<p class="bad"><?= count($report['errors']) ?> statement(s) failed:</p>
		<pre><?php foreach (array_slice($report['errors'], 0, 6) as $e) { echo ih($e), "\n"; } ?></pre>
	<?php endif; ?>

	<div class="actions">
